"""Validated ownership of persistent Q&A snapshot directories."""

import re
from pathlib import Path

from backend.app.config import QA_SNAPSHOTS_DIR


def qa_video_snapshot_dir(video_id: str, *, qa_root: Path = QA_SNAPSHOTS_DIR) -> Path:
    """Return exactly qa_root/video_id, without creating it or following aliases.

    IDs are generated by the backend, never derived from upload filenames.
    Validate Windows names on every platform so stored IDs remain portable.
    """
    if (
        not isinstance(video_id, str)
        or not re.fullmatch(r"[A-Za-z0-9_.-]+", video_id)
        or video_id in {".", ".."}
        or video_id.endswith(".")
        or video_id.split(".")[0].upper() in {
            "CON", "PRN", "AUX", "NUL",
            *(f"COM{i}" for i in range(1, 10)),
            *(f"LPT{i}" for i in range(1, 10)),
        }
    ):
        raise ValueError("Invalid Q&A video ID")
    root = Path(qa_root)
    directory = root / video_id
    for path in (root, directory):
        if path.is_symlink() or getattr(path, "is_junction", lambda: False)():
            raise ValueError("Q&A snapshot directories cannot be filesystem aliases")
    resolved_root = root.resolve()
    resolved = directory.resolve()
    if (
        resolved_root != root.parent.resolve() / root.name
        or resolved.parent != resolved_root
        or resolved.name != video_id
        or not resolved.is_relative_to(resolved_root)
    ):
        raise ValueError("Invalid Q&A snapshot directory ownership")
    return resolved
